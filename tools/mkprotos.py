#!/usr/bin/env python3
"""Write port/include/portprot.h: a prototype for every function the game's C defines.

    python3 tools/mkprotos.py

The original sources call many functions before (or without) declaring them, which Turbo
C accepts as an implicit `int f()`. On a 64-bit host an argument passed through an
implicit declaration is not narrowed to the 16-bit parameter the definition takes, so the
port declares every function with its real parameters before any code (u6.h includes this
file at its end, on the host only). Static functions are declared in a section of their
own file, selected by PORT_TU_<file> (the build defines it). Regenerate after changing a
definition.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import ctok

SKIP = {'padding.c', 'gamestat.c', 'monsdata.c', 'msgs.c'}


def definitions(src):
    """yield (is_static, text) for each function definition"""
    toks = [t for t in ctok.tokenize(src) if t[0] not in ('ws', 'nl', 'comment', 'pp')]
    depth = 0
    start = 0
    i = 0
    n = len(toks)
    while i < n:
        t = toks[i][1]
        if t == '{':
            if depth == 0 and i > 0 and toks[i - 1][1] == ')':
                decl = toks[start:i]
                yield decl
            depth += 1
        elif t == '}':
            depth -= 1
            if depth == 0:
                start = i + 1
        elif t == ';' and depth == 0:
            start = i + 1
        elif t == '=' and depth == 0:
            pass
        i += 1


def render(decl):
    out = ''
    prev = ''
    for k, t, a, b in decl:
        if out and (re.match(r'\w', t) and re.match(r'.*\w$', out) or (prev == ',' )):
            out += ' '
        elif t == '*' and out and out[-1] != '(' and out[-1] != '*':
            out += ' '
        out += t
        prev = t
    return out


def main():
    src_dir = os.path.join(ROOT, 'SRC')
    glob_lines = []
    static = {}
    for name in sorted(os.listdir(src_dir)):
        if not name.endswith('.c') or name in SKIP:
            continue
        s = open(os.path.join(src_dir, name), encoding='latin-1').read()
        for decl in definitions(s):
            words = [t[1] for t in decl]
            if 'main' in words[:3]:
                continue
            text = render(decl) + ';'
            if words[0] == 'static':
                static.setdefault(name, []).append(text)
            else:
                glob_lines.append('%s /* %s */' % (text, name))
    out = ['/* Generated by tools/mkprotos.py: prototypes of the game\'s functions, for the host',
           ' * build only (u6.h includes this file under #ifndef __TURBOC__). Do not edit. */',
           '#ifndef PORTPROT_H', '#define PORTPROT_H', '']
    out += glob_lines
    for name, lines in sorted(static.items()):
        tu = re.sub(r'\W', '_', name[:-2])
        out += ['', '#ifdef PORT_TU_%s' % tu] + lines + ['#endif']
    out += ['', '#endif', '']
    p = os.path.join(ROOT, 'port', 'include', 'portprot.h')
    open(p, 'w').write('\n'.join(out))
    print('%d global, %d static prototypes' % (len(glob_lines), sum(len(v) for v in static.values())))


if __name__ == '__main__':
    main()
