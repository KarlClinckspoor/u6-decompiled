#!/usr/bin/env python3
"""Generate the port's files for U.EXE's C (SRC_U):

    python3 port/tools/gen_u.py

  port/u/urename.h  every public name of U (its C, its assembly, its OSI library) renamed
                    U_<name>, so that U's names do not collide with GAME.EXE's, which are
                    linked into the same executable (uport.h includes it);
  port/u/uprot.h    a prototype for every function U's C defines (an argument passed through
                    an implicit declaration is not narrowed to the 16-bit parameter the
                    definition takes; u.h includes this file on the host);
  port/u/ubss.c     the uninitialised globals of SRC_U/BSS.ASM, in DOS's order, in one
                    block (as port/tools/gen_bss.py does for GAME.EXE's).

Run it again after changing U's definitions or BSS.ASM.
"""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, 'SRC_U')
OUT = os.path.join(ROOT, 'port', 'u')
sys.path.insert(0, os.path.join(ROOT, 'tools'))
sys.path.insert(0, os.path.join(ROOT, 'tools', 'u'))
import ctok  # noqa: E402
import mkprotos  # noqa: E402

PASCAL = ['OSI_callback', 'OSI_open', 'OSI_close', 'OSI_create', 'OSI_delete', 'OSI_read',
          'OSI_write', 'OSI_rename', 'OSI_copy', 'OSI_fileSize', 'OSI_memory']


def read(p):
    return open(p, encoding='latin-1').read()


def c_files(d):
    return [os.path.join(d, f) for f in sorted(os.listdir(d)) if f.lower().endswith('.c')]


def asm_files(d):
    return [os.path.join(d, f) for f in sorted(os.listdir(d)) if f.lower().endswith('.asm')]


def c_publics(path):
    """names of the non-static functions and variables a C file defines"""
    toks = [t for t in ctok.tokenize(read(path)) if t[0] not in ('ws', 'nl', 'comment', 'pp')]
    names = []
    depth = 0
    stmt = []
    for k, t, *_ in toks:
        if t == '{':
            if depth == 0 and stmt and stmt[-1] == ')':
                # a function definition: its name is the identifier before the first '('
                words = stmt
                i = words.index('(')
                if 'static' not in words[:i]:
                    names.append(words[i - 1])
                stmt = []
            depth += 1
            continue
        if t == '}':
            depth -= 1
            continue
        if depth:
            continue
        if t == ';':
            if stmt and stmt[0] not in ('extern', 'typedef', 'static') and not (
                    stmt[0] in ('struct', 'union', 'enum') and len(stmt) <= 2):
                # a variable definition (maybe with an initialiser): the declarators' names
                body = ' '.join(stmt)
                body = re.sub(r'=.*', '', body)
                if '(' not in body or re.search(r'\(\s*\*', body):
                    kw = {'int16', 'uint16', 'int32', 'uint32', 'char', 'unsigned', 'signed', 'int',
                          'long', 'short', 'void', 'far', 'near', 'struct', 'union', 'const',
                          'register', 'interrupt'}
                    for decl in body.split(','):
                        m = [x for x in re.findall(r'[A-Za-z_]\w*', decl) if x not in kw]
                        if stmt[0] in ('struct', 'union') and decl is body.split(',')[0]:
                            m = m[1:]  # the tag
                        if m:
                            names.append(m[0])
            stmt = []
            continue
        stmt.append(t)
    return names


def asm_publics(path):
    s = read(path)
    names = []
    for line in s.split('\n'):
        code = line.split(';')[0]
        m = re.match(r'\s*PUBLIC\s+(.*)', code, re.I)
        if m:
            names += [x.strip() for x in m.group(1).split(',') if x.strip()]
        m = re.match(r'\s*(?:ProcStart|FProc)\s+(\w+)', code)
        if m:
            names.append(m.group(1))
    return names


def cname(asm_name):
    return asm_name[1:] if asm_name.startswith('_') else asm_name


def public_names():
    names = set()
    for p in c_files(SRC) + c_files(os.path.join(SRC, 'OSILIB')):
        names.update(c_publics(p))
    for p in asm_files(SRC) + asm_files(os.path.join(SRC, 'OSILIB')):
        names.update(cname(n) for n in asm_publics(p))
    names.update(PASCAL)
    names.discard('main')
    return sorted(names)


def gen_rename(names):
    out = ['/* Generated by port/tools/gen_u.py: U.EXE\'s public names, renamed so that they do not',
           ' * collide with GAME.EXE\'s in the port\'s executable. Do not edit. */',
           '#ifndef U_URENAME_H', '#define U_URENAME_H']
    out += ['#define %s U_%s' % (n, n) for n in names]
    out += ['#endif', '']
    open(os.path.join(OUT, 'urename.h'), 'w').write('\n'.join(out))
    return len(names)


def gen_protos():
    glob_lines, static = [], {}
    for p in c_files(SRC):
        name = os.path.basename(p)
        for decl in mkprotos.definitions(read(p)):
            words = [t[1] for t in decl]
            if 'main' in words[:3]:
                continue
            text = mkprotos.render(decl) + ';'
            if words[0] == 'static':
                static.setdefault(name, []).append(text)
            else:
                glob_lines.append('%s /* %s */' % (text, name))
    out = ['/* Generated by port/tools/gen_u.py: prototypes of U.EXE\'s functions, for the host',
           ' * build only (SRC_U/u.h includes this file under #ifndef __TURBOC__). Do not edit. */',
           '#ifndef U_UPROT_H', '#define U_UPROT_H', '']
    out += glob_lines
    for name, lines in sorted(static.items()):
        out += ['', '#ifdef PORT_UTU_%s' % re.sub(r'\W', '_', name[:-2])] + lines + ['#endif']
    out += ['', '#endif', '']
    open(os.path.join(OUT, 'uprot.h'), 'w').write('\n'.join(out))
    return len(glob_lines)


def parse_bss():
    """[(name, label type, DOS size)] of BSS.ASM, in order"""
    objs = []
    for line in read(os.path.join(SRC, 'BSS.ASM')).split('\n'):
        code = line.split(';')[0].rstrip()
        m = re.match(r'^_(\w+)\s+LABEL\s+(\w+)', code)
        if m:
            objs.append([m.group(1), m.group(2).upper(), 0])
            continue
        m = re.match(r'^\s+ORG\s+\$\+(\d+)', code)
        if m and objs:
            objs[-1][2] += int(m.group(1))
    return objs


def declarations(names):
    """name -> 'extern <type> <declarator>' from U's C"""
    text = ''
    for p in c_files(SRC) + [os.path.join(SRC, 'u.h')]:
        text += re.sub(r'/\*.*?\*/', '', read(p), flags=re.S) + '\n'
    decl = {}
    for m in re.finditer(r'^\s*extern\s+([^;{]*);', text, re.M):
        d = m.group(1)
        b = re.match(r'((?:struct|union)\s+\w+|unsigned\s+char|signed\s+char|\w+)((?:\s+(?:far|near)\b)?)\s*(.*)', d, re.S)
        if not b:
            continue
        base, fn, rest = b.groups()
        for dec in rest.split(','):
            dec = dec.strip()
            ids = [x for x in re.findall(r'[A-Za-z_]\w*', dec) if x not in ('far', 'near', 'interrupt', 'void')]
            if ids and ids[0] in names and ids[0] not in decl:
                decl[ids[0]] = (base + fn + ' ' + dec)
    return decl


def gen_bss():
    objs = parse_bss()
    names = [o[0] for o in objs]
    decl = declarations(set(names))
    missing = [n for n in names if n not in decl]
    if missing:
        sys.exit('no C declaration for %s' % ' '.join(missing))
    arr = {n: bool(re.search(r'\b%s\s*\[\s*\]' % n, decl[n])) for n in names}
    res = {}
    with tempfile.TemporaryDirectory() as tmp:
        for bits in ('64', '32'):
            lines = ['#include "u.h"']
            for n in names:
                if not re.match(r'(console|mouseInfo)$', n):
                    lines.append('extern %s;' % decl[n])
                lines.append('int probe_%s = sizeof(%s);' % (n, n + '[0]' if arr[n] else n))
            c = os.path.join(tmp, 'p%s.c' % bits)
            open(c, 'w').write('\n'.join(lines) + '\n')
            s = os.path.join(tmp, 'p%s.s' % bits)
            target = ['-m64'] if bits == '64' else ['--target=i686-linux-gnu']
            # a minimal environment: the sizes only depend on the types
            open(os.path.join(tmp, 'stdint.h'), 'w').write(
                'typedef signed char int8_t; typedef unsigned char uint8_t; typedef short int16_t;\n'
                'typedef unsigned short uint16_t; typedef int int32_t; typedef unsigned int uint32_t;\n'
                'typedef long long int64_t; typedef unsigned long long uint64_t;\n'
                'typedef unsigned long uintptr_t; typedef long intptr_t;\n')
            open(os.path.join(tmp, 'dos.h'), 'w').write('')
            open(os.path.join(tmp, 'pc.h'), 'w').write(
                '#define far\n#define near\n#define huge\n#define pascal\n#define cdecl\n'
                '#define interrupt\n#pragma pack(1)\n')
            r = subprocess.run(['clang'] + target + ['-std=gnu89', '-fsigned-char', '-w', '-nostdinc',
                                '-I', tmp, '-I', SRC, '-I', OUT, '-include', os.path.join(tmp, 'pc.h'),
                                '-S', c, '-o', s], capture_output=True, text=True)
            if r.returncode:
                sys.exit(r.stderr[-3000:])
            cur = None
            for l in open(s).read().split('\n'):
                m = re.match(r'^_?probe_(\w+):', l)
                if m:
                    cur = m.group(1)
                    continue
                m = re.match(r'^\s*\.long\s+(\d+)', l)
                if m and cur:
                    res.setdefault(cur, {})[bits] = int(m.group(1))
                    cur = None
    entries, off = [], 0
    for name, kind, dossize in objs:
        e64, e32 = res[name]['64'], res[name]['32']
        if arr[name]:
            dos_elem = e32
            count = dossize // dos_elem
            host = count * e64 + (dossize - count * dos_elem)
        elif e64 == e32:
            host = dossize
        else:
            # near pointers are 2 bytes in DOS, far ones 4 (as -m32's)
            host = max(e64, dossize - e32 + e64)
        entries.append((name, off, host, dossize, decl[name]))
        off += host
        off = (off + 7) & ~7 if host != dossize else off
    total = (off + 15) & ~15
    out = ['/* Generated by port/tools/gen_u.py from SRC_U/BSS.ASM: do not edit.',
           ' * replaces BSS.ASM: U.EXE\'s uninitialised globals, in DOS\'s order, in one block, so',
           ' * that U\'s reads and writes past one global into the next land as in DOS. Objects',
           ' * with pointers are bigger on the host (and 8-byte aligned); every run of the others',
           ' * stays as contiguous as in DOS. */',
           '#include <stdint.h>', '',
           '#define UBSS_SIZE %d' % total,
           '__attribute__((aligned(16))) uint8_t u_bss[UBSS_SIZE];', '',
           '#if defined(__APPLE__) || (defined(_WIN32) && !defined(_WIN64))',
           '#define SYM(n) "_" #n', '#else', '#define SYM(n) #n', '#endif',
           '#define AT(n, off) __asm__(".globl " SYM(n) "\\n.set " SYM(n) ", " SYM(u_bss) " + " #off);', '']
    for name, o, host, dossize, d in entries:
        out.append('AT(U_%s, %d) /* %d bytes (DOS %d): %s */' % (name, o, host, dossize, re.sub(r'\s+', ' ', d)))
    out.append('')
    open(os.path.join(OUT, 'ubss.c'), 'w').write('\n'.join(out))
    return len(entries), total


def main():
    n = gen_rename(public_names())
    p = gen_protos()
    b, size = gen_bss()
    print('urename.h: %d names; uprot.h: %d prototypes; ubss.c: %d objects, %d bytes' % (n, p, b, size))


if __name__ == '__main__':
    main()
