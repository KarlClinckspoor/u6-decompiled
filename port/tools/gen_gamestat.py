#!/usr/bin/env python3
"""Generate port/game/gamestat_port.c from SRC/gamestat.c.

The saved game holds gamestat.c's variables as one block of bytes (GAME_Load and
GAME_Save read and write from IsOnQuest to GameStateEnd). In DOS the linker keeps them
in that order with no gaps; a host compiler does not promise that. The port therefore
defines them as one packed block, each variable an assembler symbol at its DOS offset
(the address in front of each definition), with the same initial values. The port's
build uses this file instead of SRC/gamestat.c.
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
src = open(os.path.join(ROOT, 'SRC', 'gamestat.c'), encoding='latin-1').read().replace('\r\n', '\n')
src = re.sub(r'/\*(?!([0-9A-F]{4})\*/).*?\*/', '', src, flags=re.S)
decls = re.findall(r'/\*([0-9A-F]{4})\*/\s*([^;]*?)\s*=\s*(\{.*?\}|[^;{]+);', src, re.S)
base = int(decls[0][0], 16)
fields, inits, sets, checks = [], [], [], []
for addr, decl, init in decls:
    m = re.match(r'(.*?)\b(\w+)\s*((?:\[[^\]]*\])*)$', decl.strip())
    typ, name, dims = m.group(1).strip(), m.group(2), m.group(3)
    off = int(addr, 16) - base
    fields.append('\t%s %s%s;' % (typ, name, dims))
    inits.append('\t%s,' % ' '.join(init.split()))
    sets.append('AT(%s, %d)' % (name, off))
    checks.append('_Static_assert(offsetof(struct gamestat, %s) == %d, "%s");' % (name, off, name))
out = ['/* Generated by port/tools/gen_gamestat.py from SRC/gamestat.c: do not edit.',
       ' * replaces gamestat.c on the host: its variables as one packed block, in DOS\'s order',
       ' * and at DOS\'s offsets, so the saved game\'s state block reads and writes as in DOS. */',
       '#include <stddef.h>', '#include "portable.h"', '', '#pragma pack(push, 1)', 'struct gamestat {']
out += fields + ['};', '#pragma pack(pop)', '',
                 '__attribute__((aligned(16))) struct gamestat u6_gamestat = {'] + inits + ['};', '']
out += checks + ['', '#if defined(__APPLE__)', '#define SYM(n) "_" #n', '#else', '#define SYM(n) #n', '#endif',
                 '#define AT(n, off) __asm__(".globl " SYM(n) "\\n.set " SYM(n) ", " SYM(u6_gamestat) " + " #off);', '']
out += sets + ['']
open(os.path.join(ROOT, 'port', 'game', 'gamestat_port.c'), 'w').write('\n'.join(out))
print(len(decls), 'variables')
