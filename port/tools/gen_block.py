#!/usr/bin/env python3
"""Generate port/game/<name>_port.c from SRC/<name>.c, for gamestat.c and monsdata.c.

Some of the game's data must keep DOS's layout on the host:
  - gamestat.c: the saved game holds its variables as one block of bytes (GAME_Load and
    GAME_Save read and write from IsOnQuest to GameStateEnd);
  - monsdata.c: the monster tables (far segment 3522) are read with class -1 for
    creatures that are not monsters (IsMonsterUndead(GetMonsterClass(...)) on a person),
    which in DOS reads the end of the table before.
In DOS the linker keeps each file's variables in order with no gaps; a host compiler does
not promise that. The port therefore defines them as one packed block, each variable an
assembler symbol at its DOS offset (the address in front of each definition, /*XXXX*/ or
/*SSSS:XXXX*/), with the same initial values. The port's build uses the generated file
instead of the SRC file. Unsized arrays get their size from the next variable's address;
the last one stays unsized (a flexible member).

    python3 port/tools/gen_block.py            # both files
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

SIZES = {'char': 1, 'unsigned char': 1, 'signed char': 1, 'int16': 2, 'uint16': 2,
         'int': 2, 'unsigned': 2, 'int32': 4, 'uint32': 4, 'long': 4}
ADDR = r'(?:[0-9A-F]{4}:)?([0-9A-F]{4})'


def generate(name, includes, why):
    path = os.path.join(ROOT, 'SRC', name + '.c')
    src = open(path, encoding='latin-1').read().replace('\r\n', '\n')
    # comments go, except the addresses in front of definitions
    src = re.sub(r'/\*(?!' + ADDR + r'\*/).*?\*/', '', src, flags=re.S)
    decls = re.findall(r'/\*' + ADDR + r'\*/\s*([^;=]*?)\s*=\s*(\{.*?\}|[^;{]+);', src, re.S)
    defines = re.findall(r'^#define .*$', src, re.M)
    base = int(decls[0][0], 16)
    fields, inits, sets, checks = [], [], [], []
    for i, (addr, decl, init) in enumerate(decls):
        m = re.match(r'(.*?)\b(\w+)\s*((?:\[[^\]]*\])*)$', decl.strip())
        typ, var, dims = m.group(1).strip(), m.group(2), m.group(3)
        off = int(addr, 16) - base
        if dims.startswith('[]'):
            if i + 1 < len(decls):
                size = int(decls[i + 1][0], 16) - int(addr, 16)
                dims = '[%d]' % (size // SIZES[typ]) + dims[2:]
        fields.append('\t%s %s%s;' % (typ, var, dims))
        init = re.sub(r'/\*.*?\*/', '', init, flags=re.S)
        lines = [l.strip() for l in init.strip().split('\n') if l.strip()]
        inits.append('\t' + '\n\t'.join(lines) + ',')
        sets.append('AT(%s, %d)' % (var, off))
        checks.append('_Static_assert(offsetof(struct %s, %s) == %d, "%s");' % (name, var, off, var))
    out = ['/* Generated by port/tools/gen_block.py from SRC/%s.c: do not edit.' % name,
           ' * replaces %s.c on the host: its variables as one packed block, in DOS\'s order' % name,
           ' * and at DOS\'s offsets, %s */' % why,
           '#include <stddef.h>', '#include "portable.h"'] + ['#include "%s"' % h for h in includes] + \
          [''] + defines + ['', '#pragma pack(push, 1)', 'struct %s {' % name]
    out += fields + ['};', '#pragma pack(pop)', '',
                     '__attribute__((aligned(16))) struct %s u6_%s = {' % (name, name)] + inits + ['};', '']
    out += checks + ['', '#if defined(__APPLE__) || (defined(_WIN32) && !defined(_WIN64))',
                     '#define SYM(n) "_" #n', '#else', '#define SYM(n) #n', '#endif',
                     '#define AT(n, off) __asm__(".globl " SYM(n) "\\n.set " SYM(n) ", " SYM(u6_%s) " + " #off);' % name,
                     '']
    out += sets + ['']
    dst = os.path.join(ROOT, 'port', 'game', name + '_port.c')
    open(dst, 'w').write('\n'.join(out))
    print('%s: %d variables -> %s' % (name, len(decls), os.path.relpath(dst, ROOT)))


generate('gamestat', [], "so the saved game's state block reads and writes as in DOS.")
generate('monsdata', ['monsdata.h', 'obj.h', 'spells.h'],
         'so that reads past a table (class -1) find what DOS finds.')
